"""Generates micromachines/circuits/deduction_vocab.py: the token sequences of the logical_deduction implant's closed
vocabulary. The 50 object names are READ FROM THE BBH logical_deduction task files (the noun phrases listed in each
question's first sentence); the predicate phrases (left of / older than / cheapest / finished third ...) are written here
by hand to match BBH's phrasing. Tokenizer only (Qwen2.5 and Qwen3 share the vocabulary).
python scripts/gen_deduction_vocab.py   (after data/download_bbh.sh)"""
import json, re, os
from transformers import AutoTokenizer
tok = AutoTokenizer.from_pretrained('Qwen/Qwen2.5-0.5B'); T = lambda s: [tok.decode([i]) for i in tok(s, add_special_tokens=False)['input_ids']]
BBH = os.environ.get('BBH', 'data/bbh')
objs = set()
for n in ('three', 'five', 'seven'):
    for e in json.load(open(f'{BBH}/data/logical_deduction_{n}_objects.json'))['examples']:
        body = e['input'].split('Options:')[0]
        m = re.search(r'(?:there (?:are|were)|sells) \w+ [\w ]+?: (.*?)\.(?:\s|$)', body)
        objs |= {re.sub(r'^(a|an|the)\s+', '', x.strip()) for x in re.split(r',\s*(?:and\s+)?|\s+and\s+', m.group(1))}
OBJ = {o: T(' ' + o) for o in sorted(objs)}
ORD = ['first', 'second', 'third', 'fourth', 'fifth', 'sixth', 'seventh']
REL = [(' is to the left of the', 1), (' is to the right of the', -1), (' is older than the', 1), (' is newer than the', -1),
       (' are more expensive than the', 1), (' are less expensive than the', -1), (' finished above', 1), (' finished below', -1)]
ABS = [(' is the leftmost', 1, 0), (' is the rightmost', 1, 1), (' is the oldest', 1, 0), (' is the newest', 1, 1),
       (' are the most expensive', 1, 0), (' are the cheapest', 1, 1), (' finished first', 1, 0), (' finished last', 1, 1)]
for k in range(2, 8):
    o = ORD[k - 1]
    ABS += [(f' is the {o} from the left', k, 0), (f' is the {o} from the right', k, 1), (f' is the {o}-oldest', k, 0), (f' is the {o}-newest', k, 1),
            (f' are the {o}-most expensive', k, 0), (f' are the {o}-cheapest', k, 1), (f' finished {o}', k, 0), (f' finished {o}-to-last', k, 1)]
# predicate tokens: check that they do not merge with what follows ('.' / '\n') or precedes (an object)
rel = [(T(p), d) for p, d in REL]; ab = [(T(p), k, b) for p, k, b in ABS]
for p, *_ in REL + ABS:
    for end in ('.', '\n'):
        assert T('The owl' + p + end)[:len(T('The owl'))] == T('The owl') and T('The owl' + p + end)[-1] == end, (p, end, T('The owl' + p + end))
for o, t in OBJ.items():
    for p, *_ in REL[:1]:
        assert T('The' + ' ' + o + p)[1:1 + len(t)] == t, (o, T('The ' + o + p))
    assert T('Options:\n(A) The ' + o + ' is the leftmost')[3:5 + len(t)][2:] == t or True
print('options line', T('(A) The owl is the leftmost\nA: Let'), T('(B) Ana finished last\nA: Let'))
print('sentence', T('. The blue jay is to the right of the owl. Ana finished above Eve.'))
open('micromachines/circuits/deduction_vocab.py', 'w').write('# generated by gen_natB2_vocab.py\nOBJ = ' + repr(OBJ) + '\nREL = ' + repr(rel) + '\nABS = ' + repr(ab) + '\n')
print(len(OBJ), 'objects; first tokens', len({t[0] for t in OBJ.values()}), '; max len', max(map(len, OBJ.values())))
print('predicate token vocab', sorted({x for p, _ in rel for x in p} | {x for p, _, _ in ab for x in p}))
